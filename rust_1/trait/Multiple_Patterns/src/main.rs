// === 知识点总结 ===
// 1. 元组解构绑定 (Tuple Destructuring)：使用 `let (a, b) = ...` 的语法，一次性将元组中的多个值提取并绑定到多个独立的变量上。
// 2. 结构体解构绑定 (Struct Destructuring)：在 `let` 语句中使用与结构体相同的形状，提取特定字段的值并绑定到新变量，支持变量名简写。
// 3. 多重特征约束绑定 (Multiple Trait Bounds)：在泛型编程中，使用 `+` 号将多个 Trait 组合（如 `T: TraitA + TraitB`），要求类型必须同时具备这些特征。
// 4. 多重模式匹配 (Multiple Patterns)：在 `match` 语句中，使用 `|` (或) 运算符将多个可能的值绑定到同一个处理分支。
// 5. 范围匹配 (Range Patterns)：在模式匹配中使用 `..=` 语法，匹配一个闭区间的范围。

use std::fmt::{Debug, Display};
// 知识点：模块引入。解释：引入标准库中的 Debug 和 Display 特征，用于后续的多重特征约束示例。

struct Point {
    // 知识点：结构体定义。解释：定义一个二维坐标系的点。
    x: i32, // 知识点：字段定义。解释：x 坐标。
    y: i32, // 知识点：字段定义。解释：y 坐标。
} // 知识点：作用域结束。解释：结构体定义完成。

fn print_multi_bound<T: Debug + Display>(item: &T) {
    // 知识点：多重特征约束绑定。解释：泛型 T 必须同时实现 Debug 和 Display 两个特征（用 + 连接）。
    println!("Display: {}", item); // 知识点：标准输出。解释：因为 T 实现了 Display，可以使用 `{}` 格式化打印。
    println!("Debug: {:?}", item); // 知识点：调试输出。解释：因为 T 实现了 Debug，可以使用 `{:?}` 格式化打印。
} // 知识点：作用域结束。解释：函数执行完毕。

fn main() {
    // 知识点：程序入口。解释：主函数开始执行。

    // --- 场景 1：元组的多变量解构绑定 ---
    let (a, b, c) = (1, "hello", 3.14); // 知识点：元组解构绑定。解释：将右侧元组的三个不同类型的值，一次性分别绑定给左侧的变量 a, b, c。
    println!("a: {}, b: {}, c: {}", a, b, c); // 知识点：格式化输出。解释：打印解构出来的三个独立变量。

    // --- 场景 2：结构体的解构绑定 ---
    let p = Point { x: 10, y: 20 }; // 知识点：结构体实例化。解释：创建一个 Point 实例。

    let Point { x: my_x, y: my_y } = p; // 知识点：结构体完全解构绑定。解释：将 p 中的 x 字段绑定给新变量 my_x，y 字段绑定给新变量 my_y。
    println!("my_x: {}, my_y: {}", my_x, my_y); // 知识点：格式化输出。解释：打印提取出的变量。

    let Point { x, y } = p; // 知识点：结构体解构简写绑定。解释：如果新变量名和原字段名一致，可以省略 `: 新名`，直接绑定到同名变量 x 和 y 上。
    println!("x: {}, y: {}", x, y); // 知识点：格式化输出。解释：打印简写解构出来的变量。

    // --- 场景 3：多重特征约束（泛型类型参数的多绑定） ---
    let num = 42; // 知识点：变量绑定。解释：定义一个整型变量，Rust 中的 i32 默认同时实现了 Debug 和 Display 特征。
    print_multi_bound(&num); // 知识点：泛型函数调用。解释：传入 num 的引用，完美符合 `Debug + Display` 的多重绑定要求。

    // --- 场景 4：模式匹配中的多重绑定 (Or 模式) ---
    let status = 404; // 知识点：变量绑定。解释：定义一个模拟的 HTTP 状态码。
    match status {
        // 知识点：模式匹配 (match)。解释：对 status 的值进行分支处理。
        200 | 201 | 202 => println!("Success!"), // 知识点：多重模式匹配 (Or Pattern)。解释：使用 `|` 符号，只要匹配 200, 201, 202 中的任何一个，都会绑定并执行此分支。
        400..=499 => println!("Client Error!"), // 知识点：范围模式匹配。解释：使用 `..=` 匹配 400 到 499 之间（包含首尾）的所有值。
        _ => println!("Other status"), // 知识点：通配符匹配。解释：`_` 充当 catch-all，处理所有未列出的其他情况。
    } // 知识点：作用域结束。解释：match 语句结束。
} // 知识点：作用域结束。解释：main 函数结束。
