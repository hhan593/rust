// 【知识点总结】
// 1. 条件分支 (if/else)：根据布尔值 (true/false) 决定程序的执行路径。
// 2. 严格的布尔类型：Rust 是一种强类型语言，`if` 后面的条件表达式必须严格返回 `bool` 类型，它不会像 C/C++ 那样自动将整数或对象隐式转换为布尔值。
// 3. 表达式返回值：在 Rust 中，`if` 本身是一个表达式 (Expression)。只要每个分支返回的类型相同，你就可以直接将 `if` 的结果赋值给变量。注意分支内部作为返回值的表达式不能加分号。
// 4. 模式匹配 (match)：Rust 的控制流运算符，允许你将一个值与一系列的模式进行比较，并根据匹配的模式执行相应的代码。它比连续的 `if else` 更清晰、更安全。
// 5. 穷尽性 (Exhaustiveness) 与通配符 (_)：`match` 必须覆盖所有可能的值（穷尽匹配）。对于像整数这样拥有无数种可能的值，使用 `_` 作为默认分支（通配符）来处理剩余的所有情况是必须的。

//if match                                        // 原代码注释
fn main() {                                       // 定义程序的入口点 main 函数 (知识点：程序入口)
    let age: i32 = 52;                            // 声明一个 32 位有符号整型变量 age，并赋值为 52 (知识点：变量声明与显式类型注解)

    if age < 50 {                                 // 判断 age 是否小于 50 (知识点：if 条件判断)
        println!("Your age below 50");            // 如果条件为真，执行此分支
    } else {                                      // 否则执行 else 备用分支
        println!("Your age is 50 or above");      // 如果条件为假，执行此分支
    }

    // 你新加的优秀实践：if 作为表达式！
    let msg = if age > 40 { "111" } else { "3233" }; // 判断 age>40，为真返回 "111"，为假返回 "3233"，并将结果绑定给 msg (知识点：if 表达式赋值，分支隐式返回)
    println!("{msg}");                            // 打印 msg 变量的值。这里使用了 Rust 较新的简写插值语法 {变量名} (知识点：字符串格式化简写)

    let source = 85;                              // 声明变量 source 代表分数 (知识点：类型推导)
    source_fn(source);                            // 调用 source_fn 函数 (知识点：函数调用)


    //match 匹配                                    // 原代码注释：接下来展示 match 用法
    let num = 29;                                 // 声明整型变量 num 并赋值 29 (知识点：变量绑定)

    match num {                                   // 对变量 num 的值开启模式匹配 (知识点：match 控制流)
        30 => println!("The number is 30"),       // 模式 1：如果 num 是 30，执行胖箭头 (=>) 右侧的打印语句 (知识点：match 分支与具体值匹配)
        29 => println!("The number is 29"),       // 模式 2：如果 num 是 29，执行该分支 (知识点：match 分支命中)

        _ => println!("Not the number"),          // 默认模式：通配符 `_` 会匹配以上未列出的任何其余情况，保证安全 (知识点：穷尽匹配与 _ 通配符)
    }
    // match 代码块结束 (知识点：作用域)

    //范围匹配
    // 【知识点总结】
    // 1. 范围模式匹配 (Range Patterns)：在 `match` 分支中，可以使用范围语法来一次性匹配多个连续的值，非常适合用于数字或字符的区间判断。
    // 2. 左闭右开区间 (..)：语法 `a..b` 表示匹配从 `a` 开始到 `b` 结束的区间，**包含 a 但不包含 b**（即数学中的 [a, b) ）。例如 `10..25` 匹配的是 10 到 24。
    // 3. 全闭区间 (..=)：补充知识点。语法 `a..=b` 表示**包含 a 且包含 b** 的区间（即数学中的 [a, b] ）。例如 `1..=3` 匹配 1, 2, 3。
    // 4. 占位符打印：在 `println!` 宏中使用 `{}` 作为占位符，将后面的变量按顺序填入字符串中输出。

    fn main() {                                         // 定义程序的入口函数 main
        let num = 28;                                   // 声明一个测试用的变量 num，并赋值为 28 (你可以尝试修改这个值看看不同的输出)

        match num {                                     // 对变量 num 的值开启模式匹配 (知识点：match 控制流)
            10..25 => println!("The number is {}", num), // 匹配区间 [10, 25)：如果 num 在 10 到 24 之间，命中此分支并打印 (知识点：左闭右开区间 ..)
            25..30 => println!("The number is {}", num), // 匹配区间 [25, 30)：如果 num 在 25 到 29 之间，命中此分支 (因为 num 是 28，程序将执行这行)
            30..60 => println!("The number is {}", num), // 匹配区间 [30, 60)：如果 num 在 30 到 59 之间，命中此分支 (知识点：连续区间匹配)
            _ => println!("Not the number"),            // 默认分支：如果 num 不在 10 到 59 之间，通配符 `_` 捕获剩余所有情况 (知识点：穷尽匹配与通配符)
        }                                               // match 代码块结束
    }
    let rss = match num {
        x if x < 60 => "lucky".to_owned(),
        x if x > 60 => "bad".to_owned(),
        _ => "".to_owned(),
    };
    println!("{}", rss);
    let char = 'c';
    match char {
        'a'..='j' => println!("属于前半段小写字母"),
        'k'..='z' => println!("属于后半段小写字母"),
        _ => println!("不是小写字母"),
    }
}

