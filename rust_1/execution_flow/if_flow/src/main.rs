fn source_fn(source: i32) {                       // 定义接收 i32 参数的 source_fn (知识点：函数定义)

    if source < 0 || source > 100 {               // 使用 || 检查分数是否越界 (知识点：逻辑或)
        println!("请输入正确的分数");               // 异常提示
    } else {                                      // 分数合法进入正常判定逻辑

        if source < 60 {                          // 判断是否低于 60
            println!("你不及格")                    // 低于 60 的提示
        } else if source < 80 {                   // 判断是否在 60 到 79 分之间 (知识点：else if 链式判定)
            println!("很不错")                     // 中等分数提示
        } else {                                  // 剩余的高分段 (80-100)
            println!("真牛逼")                     // 高分提示
        }
    }                                             // else 分支结束
}                                                 // 函数结束