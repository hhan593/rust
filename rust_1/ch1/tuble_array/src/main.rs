fn main() {
    // =========================================================================
    // 👑 第一部分：复合类型 (Compound Types) —— 数组与元组
    // =========================================================================

    // ------------------------------------------
    // 1. 数组 (Array)：固定长度的【同构】集合
    // ------------------------------------------
    // 💡 [底层逻辑]：数据全部分配在栈(Stack)上，长度不可变，类型必须绝对统一。

    // 创建方式 1：逐个枚举
    let arr1 = [1, 2, 3, 4, 5];

    // 创建方式 2：批量初始化 [默认值; 长度]
    // 这相当于写了 let arr_batch = [5, 5, 5];
    let _arr_batch = [5; 3];

    // 获取元素（索引从 0 开始）与获取长度
    let first = arr1[0];
    let first_length = arr1.len();

    println!("--- 数组演示 ---");
    println!("arr1 的第一个元素: {}", first);
    println!("arr1 的长度: {}", first_length);

    // 【可变数组】
    // 💡 [进阶]：加了 mut 只能修改里面的值，但绝对不能使用 push 之类的方法增加长度
    // 如果需要长度可变的数组，在 Rust 中叫 Vec (动态数组/向量)，分配在堆区。
    let mut arr2 = [1, 2, 3, 4, 5];
    arr2[3] = 20;
    println!("修改后的 arr2[3]: {}", arr2[3]);

    // 【遍历数组】
    // 这里因为是基础 i32 类型，遍历时自动进行了 Copy
    for ele in arr2 {
        println!("arr2 的元素: {}", ele);
    }

    // ------------------------------------------
    // 2. 元组 (Tuple)：固定长度的【异构】组合
    // ------------------------------------------
    // 💡 [底层逻辑]：长度依然不可变，但里面可以塞完全不同类型的数据。

    // 编译器会自动推导出类型：(i32, f64, i32, &str)
    let tup = (500, 6.4, 1, "Hello");

    println!("\n--- 元组演示 ---");
    // 获取元素：必须使用点号 `.` 加上索引
    // ⚠️ 注意：元组没有 .len() 方法！
    println!("tup 的第一个元素: {}", tup.0);

    // 【可变元组】
    // 💡 [进阶]：修改的值，必须跟该位置一开始的类型一模一样（比如 tup.0 必须是整数）
    let mut tuple1 = (500, 6.4, 1, "Hello");
    tuple1.0 = 8000;
    println!("修改后的 tuple1.0: {}", tuple1.0);

    // 【空元组】 Unit Type `()`
    // 💡 [进阶]：极其特殊的存在。如果函数没有写返回值，默认就是隐式返回 ()
    let tup3 = ();
    println!("tup3 (空元组): {:?}", tup3);

    // =========================================================================
    // 👑 第二部分：所有权机制 (Ownership) —— 栈与堆的狂舞
    // =========================================================================
    println!("\n--- 所有权演示 ---");

    // ------------------------------------------
    // 场景 A：Move (所有权转移) —— 针对堆区复杂数据
    // ------------------------------------------
    // s1 在堆上分配了内存
    let s1 = String::from("hello");

    // 💡 [底层逻辑]：发生 Move。s1 连同它的内存一起“过户”给了 s2。
    // Rust 为了防止 s1 和 s2 两次释放同一块内存，直接“击毙”了 s1。
    let s2 = s1;

    // ❌ 取消下面这行的注释会报错：borrow of moved value: `s1`
    // println!("s1 已经阵亡: {}", s1);

    // ✅ s2 是合法的新主人
    println!("s2 活得很好: {}", s2);

    // ------------------------------------------
    // 场景 B：Copy (完美复印) —— 针对栈区基础数据
    // ------------------------------------------
    let x = 5;

    // 💡 [底层逻辑]：发生 Copy。因为 i32 是极其简单的数据，全在栈上。
    // Rust 认为复印它的代价极低，于是直接印了一份给 y。
    let y = x;

    // ✅ x 和 y 岁月静好，互不干涉
    println!("x = {}, y = {} (我们都活着)", x, y);

    // ------------------------------------------
    // 场景 C：Borrowing (借用/引用) —— 借来看一眼
    // ------------------------------------------
    let my_string = String::from("Rust真好玩");

    // 💡 [底层逻辑]：加了 `&`，表示生成一个“借条”。
    // 把借条传给函数，原主人的所有权并没有丢失！
    let length = calculate_length(&my_string);

    // ✅ 因为只是借出去了一下，my_string 依然可以安全使用
    println!("'{}' 的长度是 {}", my_string, length);
}

// =========================================================================
// 👑 辅助函数区
// =========================================================================

// 接收一个 String 的【不可变引用】(&)
// 意味着：只能看，不能改，且不拿走所有权。
fn calculate_length(s: &String) -> usize {
    s.len()
} // 函数结束，s (借条) 被销毁，原变量无事发生。
