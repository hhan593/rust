// 【知识点总结】
// 1. 派生宏 (Derive Macro)：利用 #[derive(Debug)] 让自定义类型支持被打印调试。
// 2. 自定义结构体 (Struct)：允许将多个相关的值打包成一个有意义的组合。
// 3. 所有权机制 (Ownership) 与 Move 语义：Rust 内存安全的核心。对于分配在堆上的数据（如 Vec）或未实现 Copy trait 的结构体，赋值操作默认是“移动” (Move)，原变量会失效。
// 4. 深拷贝 (Clone)：通过调用 .clone() 方法，可以在堆内存中复制一份完全独立的数据，从而避免所有权转移导致的原变量失效。
// 5. 堆 (Heap) 与栈 (Stack)：像动态数组 (Vec) 长度可变，数据存放在堆上；基本类型数据的指针、长度等元数据存在栈上。

#[derive(
    Debug
)]                          // 让编译器自动为 Book 结构体实现 Debug trait，以便能够使用 {:?} 格式化打印 (知识点：派生宏 Derive Macro, Debug trait)
struct Book {                             // 定义一个名为 Book 的自定义结构体，用于组合相关数据 (知识点：结构体 Struct 定义)
    page: i32,                            // 定义名为 page 的结构体字段，类型为 32 位有符号整数 (知识点：结构体字段，基本数据类型 i32)
    rating: f64,                          // 定义名为 rating 的结构体字段，类型为 64 位浮点数 (知识点：结构体字段，基本数据类型 f64)
}                                         // 结束 Book 结构体的定义作用域 (知识点：语法与作用域)

fn main() {                               // 定义程序的入口函数 main (知识点：入口函数)
    //存储在堆上                            // 原代码注释：提示接下来的变量涉及到堆内存分配

    let x = vec![1, 2, 3];                // 使用 vec! 宏创建一个包含 3 个元素的动态数组，数据分配在堆上，并将其绑定到变量 x (知识点：动态数组 Vec, 宏 macro, 堆内存分配)
    let y = x;                            // 将 x 赋值给 y。因为 Vec 数据在堆上，这里发生所有权转移 (Move)，x 在此之后失效 (知识点：所有权转移 Move 语义)
    println!("{:?}", y);                  // 使用 println! 宏以 Debug 格式 ({:?}) 打印变量 y 的值 (知识点：格式化输出，宏的使用)

    // println!("{:?}", x); //因为x的所有权已经到y了 // 原代码注释/代码：如果取消注释，编译器借用检查器会报错，因为 x 的所有权已转移 (知识点：编译期借用检查机制 Borrow Checker)

    // 但是可以通过clone来解决这个问题          // 原代码注释：引出深拷贝的概念
    let c = y.clone();                    // 调用 y 的 clone 方法在堆上创建一份完全相同的数据副本并绑定给 c，y 不会失效 (知识点：深拷贝 Clone trait)
    println!("{:?}", c);                  // 打印新克隆出来的变量 c 的值 (知识点：格式化输出)
    println!("{:?}", y);                  // 打印 y 的值，证明克隆操作后原变量依然有效，拥有自己独立的数据 (知识点：Clone 操作后的所有权状态)


    let b1 = Book { page: 3, rating: 1.0 }; // 实例化 Book 结构体，分配具体的值，并绑定给不可变变量 b1 (知识点：结构体实例化)
    let b2 = b1; //move                   // 将 b1 赋值给 b2。因为 Book 未实现 Copy trait，此处也发生所有权转移 (Move) (知识点：自定义类型的 Move 语义)

    // println!("{:?}", b1); //所有权已转移   // 原代码注释/代码：因为所有权已移交给 b2，此时访问 b1 会导致编译错误 (知识点：失效变量访问报错)
    println!("{:?}", b2);                 // 打印拥有结构体实例所有权的变量 b2 (知识点：格式化输出)

}                                         // main 函数作用域结束，变量 b2, c, y 依次离开作用域，触发 Drop 释放其占用的内存 (知识点：作用域结束，Drop trait 自动内存回收)