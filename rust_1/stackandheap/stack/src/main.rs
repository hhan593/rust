// 【知识点总结】
// 1. 结构体 (Struct)：定义自定义数据类型，用于将多个相关的基础数据聚合在一起。
// 2. Box 智能指针：Rust 中最基础的智能指针，用于将数据强制分配在 堆 (Heap) 上，而 Box 指针本身（包含堆内存的地址）存储在 栈 (Stack) 上。
// 3. 自动解引用 (Auto-deref)：通过 Box 指针直接访问结构体内部字段时，Rust 编译器会自动进行解引用操作，简化了代码书写。
// 4. 解引用运算符 (*)：用于显式追踪指针，获取或修改智能指针所指向的堆内存中的实际底层数据。
// 5. 可变性 (Mutability)：结合 mut 关键字，可以声明一个可变的 Box 指针，从而允许通过解引用来修改堆内存中的数据。
// 6. 内存管理：当 Box 变量离开作用域时，Rust 会自动调用 Drop trait，安全释放其在堆上占用的内存，无需手动 free。

struct Point {                                 // 定义一个名为 Point 的结构体 (知识点：结构体 Struct 定义)
    x: i32,                                    // 声明结构体字段 x，类型为 32 位有符号整型 (知识点：结构体字段，基本数据类型 i32)
    y: i32,                                    // 声明结构体字段 y，类型为 32 位有符号整型 (知识点：结构体字段，基本数据类型 i32)
}                                              // 结构体定义作用域结束 (知识点：语法与作用域)

/**
 * 主函数                                       // 程序的入口函数注释
 * 演示了Box智能指针的基本使用，包括在堆上分配内存和访问堆上的数据
 */
fn main() {                                    // 定义程序的入口函数 main (知识点：入口函数)
    //Box智能指针，用于在堆上分配内存，              // 原代码注释
    let b = Box::new(5);                       // 调用 Box::new 将整数 5 分配在堆上，并将指向该堆内存的指针绑定到不可变变量 b (知识点：Box 堆分配，变量绑定)
    println!("b = {}", b);                     // 打印变量 b 的值，Box 实现了 Display trait 允许直接打印 (知识点：格式化输出，宏的使用)

    let pointer = Box::new(Point { x: 0, y: 0 }); // 在堆上实例化 Point 结构体，并将智能指针绑定到 pointer 变量上 (知识点：结构体实例化，复杂类型的堆分配)

    println!("x {} y {}", pointer.x, pointer.y); // 打印结构体字段。注意：这里发生了隐式的自动解引用，等价于 (*pointer).x (知识点：自动解引用特性)

    let mut box_point = Box::new(32);          // 将整数 32 分配在堆上，并绑定到可变变量 box_point，允许修改堆内存中的值 (知识点：可变变量 mut，Box 堆分配)

    // &取地址 *取值                              // 原代码注释：提示引用和解引用的符号
    println!("{}", *box_point);                // 使用 * 运算符显式解引用，获取并打印 box_point 指向的堆内存中的数值 32 (知识点：解引用运算符 *)

    *box_point += 10;                          // 先解引用拿到堆上的值，再将其增加 10，此时堆中的数据被修改为 42 (知识点：解引用修改数据，复合赋值运算)
    println!("{}", *box_point);                // 再次解引用并打印修改后的最新值 42 (知识点：解引用运算符 *)
}                                              // main 函数结束，变量 box_point, pointer, b 依次离开作用域，触发自动清理 (知识点：Drop trait 自动释放堆内存)

