// 【知识点总结】
// 1. 函数定义与返回值：使用 `-> Type` 声明返回值类型。函数体最后一行不加分号即可作为表达式隐式返回。
// 2. 按值传递 (Copy 语义)：对于像 `i32` 这样的基础数据类型（实现了 Copy trait），传参时默认会**复制**一份数据给函数。函数内部怎么修改，都不会影响外面的原变量。
// 3. 局部可变参数 (`mut x`)：在函数参数前加 `mut`，仅仅代表这个参数在**函数内部**是可以被修改的，它依然是外面数据的副本，不改变外部数据。
// 4. 按可变引用传递 (`&mut x`)：传递变量的内存地址，允许函数直接操作并修改外部原变量的值。
// 5. 解引用 (`*`)：当传入的是引用（指针）时，必须使用解引用符 `*` 追踪到具体的内存地址，才能修改里面的真实数据。
// 6. 自定义类型的 Copy 语义：默认情况下，自定义的 `struct` 传参时会发生所有权转移 (Move)。但如果它的所有字段都是基础类型（如 `i32`），可以通过派生宏 `#[derive(Copy, Clone)]` 让它像整数一样进行复制，从而避免所有权丢失。

#[derive(
    Copy,
    Clone
)]                      // [核心新增] 使用派生宏让编译器自动为 Point 实现 Copy 和 Clone 特型。前提是其内部字段 (i32) 本身也是 Copy 的 (知识点：派生宏 Derive Macro，特型推导)
struct Point {                              // 定义名为 Point 的结构体 (知识点：结构体定义)
    x: i32,                                 // i32 实现了 Copy (知识点：结构体字段)
    y: i32,                                 // i32 实现了 Copy (知识点：结构体字段)
}                                           // 结构体作用域结束

fn print_point(point: Point) {              // 定义接收 Point 类型的函数。注意：因为 Point 实现了 Copy，这里接收的是外边数据的**副本**，而不是拿走了所有权 (知识点：Copy 语义传参)
    println!("x: {}, y: {}", point.x, point.y); // 打印副本字段的值 (知识点：格式化输出，访问结构体字段)
}                                           // 函数结束，副本被销毁，对外部原变量无影响

fn add(x: i32, y: i32) -> i32 {             // 定义 add 函数，接收两个 i32 参数，箭头 -> 表示该函数会返回一个 i32 类型的值 (知识点：函数签名与返回值类型)
    x + y                                   // 将 x 和 y 相加。注意：这里**没有分号**，代表这是一个表达式，其计算结果会被隐式返回给调用者 (知识点：表达式与隐式返回)
}

fn change(mut x: i32) {                     // 定义 change 函数。`mut x` 表示传入的参数 x 在这个函数内部可以被修改。但请记住，这里的 x 只是外面变量 c 的一个**克隆体（副本）** (知识点：函数参数的局部可变性)
    x = x + 8;                              // 将副本 x 的值增加 8 (变成了 9)
    println!("{}", x);                      // 打印副本 x 的值，这里会输出 9。但一旦函数结束，这个副本 x 就会被销毁，对外界毫无影响 (知识点：局部变量生命周期)
}

fn modify(x: &mut i32) {                    // 定义 modify 函数。参数签名 `&mut i32` 明确表示它接收的是一个**指向 i32 数据的可变指针/引用** (知识点：可变引用参数)
    *x += 5;                                // 解引用操作：使用 `*x` 顺着指针找到堆栈里那个真实的变量 c，并把它里面的值加上 5。这叫“就地修改” (知识点：解引用赋值)
}


fn main() {                                 // 定义程序的入口点 main 函数 (知识点：程序入口)
    let count = add(12, 56);                // 调用 add 函数，传入两个 i32 整数，将返回的结果绑定到 count 变量 (知识点：函数调用与返回值绑定)
    println!("{}", count);                  // 打印 count 的值，结果应该是 68 (知识点：格式化输出)

    let mut c = 1;                          // 声明一个可变变量 c，初始化为 1 (知识点：可变变量声明)

    change(c);                              // 调用 change 函数。注意：因为 i32 实现了 Copy，这里实际上是把 c 的值 (1) **复制**了一份传进函数，原变量 c 并没有交出所有权，也不受影响 (知识点：Copy trait 与按值传递)
    println!("{}", c);                      // 打印 c 的值。因为上面是按值传递的复制，c 的真实值没有任何改变，依然打印 1 (知识点：作用域与值隔离)

    modify(&mut c);                         // 调用 modify 函数。这里传入的是 c 的**可变引用（地址）**，允许 modify 函数去内存里修改 c 本身 (知识点：按可变引用传递借用)
    println!("{}", c);                      // 打印 c 的值。此时 c 的真实数据已经被 modify 函数修改过了，打印出 6 (知识点：可变借用生效)


    let point = Point { x: 1, y: 2 };       // 实例化 Point 结构体，分配具体值并绑定到变量 point (知识点：结构体实例化)

    print_point(point);                     // [逻辑纠正] 函数调用。由于 Point 加了 `#[derive(Copy)]`，这里发生的是底层二进制的按位复制 (Copy)！外面的 point 变量**并未**失去所有权。(知识点：Copy trait 防止所有权转移)

    //  正因为所有权没有丢失，可以正常打印出 1。
    println!("point.x {}", point.x);        // 此时依然拥有所有权，可以直接访问原变量的字段并打印 (知识点：所有权保留后的字段访问)
}