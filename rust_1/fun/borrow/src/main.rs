// 【知识点总结】
// 1. 所有权转移 (Move)：将非 Copy 类型（如 String）按值传递给函数时，所有权会转移到函数内部，原变量随即失效。
// 2. 拷贝语义 (Copy)：基础类型（如 i32、f64、bool 等）默认实现了 Copy，按值传参时发生的是复制，不影响原变量。
// 3. 不可变借用 (&T)：允许读取数据而不获取所有权，同一时刻可以有多个不可变借用。
// 4. 可变借用 (&mut T)：允许修改借用的数据，但同一时刻只能有一个活跃的可变借用（防止数据竞争）。
// 5. 自动解引用 (Auto-deref)：对于结构体的指针/引用，Rust 允许直接使用 `p.y` 访问字段，编译器会自动将其转换为 `(*p).y`。
// 6. 借用的非词法作用域生命周期 (NLL) 与独占性：同一作用域内绝对只能存在一个活跃的可变引用。但只要两次借用的“使用时间”不重叠，就可以先后合法借用。也可以使用大括号 `{}` 强制隔离作用域提前归还借用。

fn main() {
    // 定义程序的入口点 main 函数 (知识点：程序入口)
    //函数的可变借用与不可变借用                  // 原代码注释
    let p1 = 12; // 声明 i32 变量 p1。i32 实现了 Copy 特型 (知识点：栈上数据，Copy 语义)
    let p2 = String::from("hello"); // 声明 String 变量 p2。String 数据在堆上，未实现 Copy (知识点：堆分配数据，Move 语义)

    move_func(p1, p2); // 调用函数。p1 传入的是副本 (Copy)；p2 传入的是本体，发生所有权转移 (Move) (知识点：传参的所有权行为)

    println!("{}", p1); // 正常打印 p1，因为前面只是复制了它的值，p1 依然有效 (知识点：Copy 类型的值保留)
                        // println!("{}", p2); //为什么p2会报错呢？  // 原代码注释：由于 p2 在上一行已经把所有权 Move 给了 move_func，此时 p2 处于未初始化/已失效状态，编译器强制拦截以保证内存安全 (知识点：Use after move 拦截)

    let mut p2 = String::from("hello"); // 重新声明一个同名的可变变量 p2（变量遮蔽 Shadowing），并分配新的堆内存 (知识点：变量遮蔽，可变绑定)

    print_string(&p2); //不可变借用,只是用他这个值，但是如果是可变借用就是不行的 // 原代码注释：传递不可变引用 &p2
    println!("{}", p2); // 不可变借用结束后，p2 的所有权还在自己手里，可以正常打印 (知识点：借用归还)

    print_string_variable(&mut p2); // 传递可变引用 &mut p2，允许函数内部修改这个字符串 (知识点：按可变引用传递)

    let mut person = Person { x: 10, y: 20 }; // 实例化自定义的 Person 结构体，并绑定到可变变量 person 上 (知识点：结构体可变实例化)
    print!("{:?}", person); // 使用 Debug 格式 {:?} 打印修改前的 person 状态 (知识点：格式化输出)

    modify_person(&mut person); // 将 person 的可变借用（地址）传给修改函数 (知识点：可变引用传参)
    println!("{:?}", person); // 打印修改后的状态，此时 x 变成了 100，y 变成了 120 (知识点：跨函数就地修改生效)

    // ==========================================       // 分隔线
    // 演示：可变借用的独占性与生命周期机制 (新增整合)      // 模块说明注释
    // ==========================================       // 分隔线

    let mut s = String::from("hello"); // 在堆上分配一个可变字符串 s (知识点：可变变量声明与堆分配)

    // ❌ 错误示范：尝试同时持有两个可变借用
    // let r1 = &mut s;                                 // 第一把“写入锁”：r1 获取了 s 的可变借用
    // let r2 = &mut s;                                 // 第二把“写入锁”：r2 试图再次获取 s 的可变借用
    // println!("{}, {}", r1, r2);                      // 编译直接报错！报错信息："cannot borrow `s` as mutable more than once at a time"

    // ✅ 正确示范 1：利用 NLL（使用完毕即释放借用）
    let ref1 = &mut s; // 创建第一个可变借用 ref1 (知识点：建立可变借用)
    ref1.push_str(" world"); // 通过 ref1 修改堆内存中的字符串数据 (知识点：通过引用修改数据)
    println!("ref1: {}", ref1); // 打印 ref1。注意：**这是 ref1 最后一次出现！** 生命周期在此结束 (知识点：引用的非词法作用域终结 NLL)

    let ref2 = &mut s; // 因为上一个借用 ref1 已经“死”了，这里再次创建可变借用 ref2 完全合法 (知识点：借用生命周期不重叠)
    ref2.push_str("!"); // 通过 ref2 再次追加字符 (知识点：合法修改)
    println!("ref2: {}", ref2); // 打印 ref2，此时字符串已变为 "hello world!" (知识点：控制流正常执行)

    // ✅ 正确示范 2：利用大括号人为隔离作用域
    let mut data = 10; // 声明普通的整数可变变量 data (知识点：可变绑定)
    {
        // 开启一个内部的代码块作用域 (知识点：词法作用域控制)
        let block_ref = &mut data; // 在内部作用域获取可变借用 (知识点：局部借用)
        *block_ref += 5; // 解引用并修改数值 (知识点：解引用赋值)
    } // 内部大括号结束，block_ref 随之强制销毁，data 的借用状态被释放 (知识点：作用域终结与借用强制归还)

    let out_ref = &mut data; // 内部借用已归还，外面再次获取可变借用毫无阻力 (知识点：安全重借用)
    *out_ref += 5; // 再次解引用并增加 5 (知识点：解引用赋值)
    println!("data: {}", out_ref); // 最终打印结果为 20 (知识点：格式化输出)
}

fn move_func(p1: i32, p2: String) {
    // 接收一个 i32 (复制) 和一个 String (获取所有权)
    println!("move_func({}, {})", p1, p2); // 打印这两个值
} // 函数结束！注意：p2 的生命周期在这里走到尽头，它背后的堆内存被自动 Drop 释放！(知识点：作用域结束，所有权释放)

//i32已经实现了Copy特性                        // 原代码注释
fn print_value(val: i32) {
    // 接收 i32 副本
    println!("print_value({})", val); // 打印副本
}

fn print_string(val: &String) {
    // 接收 String 的不可变借用 &String
    // (*val) 是显式解引用拿到真实 String，然后再调用 to_uppercase。
    // 其实在 Rust 中直接写 val.to_uppercase() 也是可以的，因为有自动解引用特性
    println!("print_string({})", (*val).to_uppercase()); // 打印转化为大写后的字符串 (知识点：显式解引用，字符串方法)
}

fn print_string_variable(val: &mut String) {
    // 接收 String 的可变借用 &mut String
    println!("print_string_variable({})", val); // 打印当前值。由于参数是 &mut String，允许直接修改内部数据 (知识点：可变借用的使用)
}

#[derive(Debug)] // 派生宏，让编译器自动实现打印调试信息的代码 (知识点：Derive 宏)
struct Person {
    // 定义结构体 Person
    x: i32,
    y: i32,
}

fn modify_person(p: &mut Person) {
    // 接收 Person 的可变指针 &mut Person
    (*p).x = 100; // 严谨的底层写法：先用 * 解引用拿到实例，再用 . 访问字段 x 并修改 (知识点：显式解引用修改字段)

    // Rust 语法糖：对于结构体的指针，可以省略 * 号，直接用 . 访问。
    // 编译器发现 p 是指针，会自动帮你变成 (*p).y
    p.y += 100; // 自动解引用写法：等价于 (*p).y = (*p).y + 100 (知识点：编译器自动解引用 Auto-deref)
}
