// 【知识点总结】
// 1. self 接收者：按值传递 `self`。调用方法时会发生所有权转移 (Move)，原实例将被消费，调用后无法再次访问。常用于将实例转换为另一种类型的构造或收尾操作。
// 2. &self 接收者：不可变借用。只读访问实例数据，不获取所有权。同一时刻可以存在多个不可变借用，非常适合普通的数据读取方法。
// 3. &mut self 接收者：可变借用。允许在方法内部修改实例的数据。根据 Rust 的借用规则，同一时刻只能存在一个活动的可变借用，且不能与不可变借用共存。
// 4. 关联函数 (Associated Functions)：没有 self 参数的函数，通常用作构造器 (如 new) 或特定命名空间的辅助工具。
// 5. 编译期借用检查 (Borrow Checker)：被 Move 之后的变量，或者违反读写借用冲突的代码，会在编译阶段被拦截，从而保证内存安全。

// ================================================================ // 原代码分隔线
// self / &self / &mut self 三种参数形式的语义对照                    // 原代码注释
// ================================================================ // 原代码分隔线
// self      === (self: Self)   → Move 所有权转移，调用后实例被消费    // 原核心笔记：等价于按值传递，消耗实例
// &self     === (self: &Self)  → 不可变引用（共享借用），可多次借用   // 原核心笔记：等价于传入不可变指针，只读
// &mut self === (self: &mut Self) → 可变引用（独占借用），同一时刻只有一个 // 原核心笔记：等价于传入可变指针，可修改数据
// ================================================================ // 原代码分隔线

struct Point {                                                       // 定义名为 Point 的结构体 (知识点：结构体定义)
    x: f64,                                                         // 定义字段 x，类型为 64 位浮点数 (知识点：结构体字段)
}                                                                   // 结构体作用域结束 (知识点：作用域)

impl Point {                                                        // 为 Point 开启实现块 (知识点：impl 块)
    // self: 所有权转移 —— 调用后 point 被 move 进函数，外界不能再使用  // 原代码注释
    // 等价写法: fn get(self) -> f64                                  // 原代码注释
    fn get(self: Self) -> f64 {                                     // 定义方法 get，接收 self 按值传递（所有权转移） (知识点：消耗型方法 self)
        self.x                                                      // 返回字段 x 的值，由于没有分号，这是一个隐式返回表达式 (知识点：隐式返回，结构体字段读取)
    }                                                               // get 方法结束，此时传入的 Point 实例（self）随着作用域结束被释放 (Drop) (知识点：所有权释放)
}                                                                   // Point 实现块结束 (知识点：作用域)

struct Counter {                                                    // 定义名为 Counter 的结构体，用于计数 (知识点：结构体定义)
    number: i32,                                                    // 包含一个 32 位整型数据 number (知识点：结构体字段)
}                                                                   // 结构体作用域结束 (知识点：作用域)

impl Counter {                                                      // 为 Counter 开启实现块 (知识点：impl 块)
    // 关联函数（不是方法）：没有 self 参数，通过 Counter::new(...) 调用 // 原代码注释
    fn new(number: i32) -> Counter {                                // 定义关联函数 new，接收整型参数并返回 Counter 实例 (知识点：关联函数作为构造器)
        Counter { number }                                          // 实例化 Counter 并隐式返回，使用字段名简写语法 (知识点：结构体实例化，隐式返回)
    }                                                               // new 函数结束 (知识点：作用域)

    // &self: 不可变借用 —— 只读访问，不消耗实例，可多次调用,只能读       // 原代码注释
    fn get_number(&self) -> i32 {                                   // 定义方法 get_number，接收不可变引用 &self (知识点：不可变借用方法 &self)
        self.number                                                 // 读取并隐式返回 number 字段，注意这里 i32 实现了 Copy trait，所以直接复制返回值 (知识点：自动解引用读取，Copy 语义)
    }                                                               // get_number 结束，借用归还 (知识点：引用的生命周期)

    // self: 所有权转移 —— 调用后实例被消费，不能再使用                 // 原代码注释
    fn give_up(self) {                                              // 定义方法 give_up，按值接收 self，发生 Move (知识点：消耗型方法 self)
        println!("Give up {}", self.number);                        // 打印传入实例的数字 (知识点：格式化输出)
    }                                                               // give_up 结束，传入的实例在此被彻底销毁 (Drop) (知识点：内存释放)

    // &mut self: 可变借用 —— 可修改字段，同一时刻只能有一个可变引用      // 原代码注释
    fn add(&mut self, increment: i32) {                             // 定义方法 add，接收可变引用 &mut self 和增加量 (知识点：可变借用方法 &mut self)
        self.number += increment                                    // 修改自身引用的 number 字段的值 (知识点：通过可变引用修改内部状态)
    }                                                               // add 结束，可变借用归还 (知识点：可变引用的生命周期)

    // 无 self: 关联函数，接收两个 Counter 的所有权，返回新的 Counter    // 原代码注释
    // c1 和 c2 都被 move 进函数，调用后二者均被消费                    // 原代码注释
    fn combined(c1: Counter, c2: Counter) -> Counter {              // 定义关联函数 combined，按值接收两个 Counter 实例，它们的所有权均转移到函数内 (知识点：多参数所有权转移)
        Counter {                                                   // 构造一个新的 Counter 实例 (知识点：结构体实例化)
            number: c1.number + c2.number,                          // 将传入的两个实例的 number 相加，作为新实例的 number (知识点：算术运算与赋值)
        }                                                           // 隐式返回新构造的 Counter 实例 (知识点：隐式返回)
    }                                                               // combined 结束，c1 和 c2 未被返回的部分会被清理 (此处仅有整型数据，随作用域销毁) (知识点：所有权终结)
}                                                                   // Counter 实现块结束 (知识点：作用域)

fn main() {                                                         // 定义程序的入口点 main 函数 (知识点：程序入口)
    // ---- 示例1: &self 不可变借用 ----                              // 原代码注释分界线
    let c = Counter::new(10);                                       // 调用关联函数创建一个 number 为 10 的不可变 Counter 实例，绑定到 c (知识点：实例创建)
    println!("c.number = {}", c.get_number());                      // 调用接收 &self 的方法，只读借用 c (知识点：不可变方法调用，自动传递 &c)
    println!("c.number = {}", c.get_number());                      // 再次调用 &self 方法。不可变借用允许多次同时存在或先后存在 (知识点：不可变引用的共享性)
    c.give_up();                                                    // 调用接收 self 的方法。c 的所有权被 Move 进 give_up 函数 (知识点：方法调用导致所有权转移)

    // ---- 示例2: &mut self 可变借用 ----                            // 原代码注释分界线
    let mut c = Counter::new(5);                                    // 创建一个可变的 Counter 实例，必须使用 mut 关键字修饰变量 (知识点：可变变量声明)
    println!("before add: {}", c.get_number());                     // 发生一次不可变借用读取初始值 (知识点：不可变方法调用)
    c.add(3);                                                       // 发生一次可变借用调用 add。此时之前的不可变借用已结束 (NLL 机制)，合法 (知识点：可变方法调用，自动传递 &mut c)
    println!("after add: {}", c.get_number());                      // 可变借用结束，再次发起不可变借用读取修改后的值 (知识点：借用交替，作用域规则)

    // 注意: 下面两行不能同时存在，因为 get_number(&self) 和 add(&mut self) 交替时 // 原代码注释说明借用的非词法作用域生命周期 (NLL)
    // 不可变借用已结束，所以这里没问题                                  // 原代码注释说明
    c.give_up();                                                    // 消耗掉当前可变的 c 实例的所有权 (知识点：可变实例同样可以按值转移所有权)

    // ---- 示例3: self 所有权转移 —— compile error if used after ---- // 原代码注释分界线
    let c = Counter::new(42);                                       // 创建一个新的 Counter 实例 (知识点：实例创建)
    c.give_up();                                                    // c 的所有权转移到了 give_up 函数内部并被销毁 (知识点：所有权 Move)
    // println!("{}", c.get_number()); // 编译错误！c 已被 move       // 原代码注释：由于上一行发生 Move，此时 c 已处于未初始化/无效状态，借用检查器拒绝编译 (知识点：Use after move 错误拦截)

    // ---- 示例4: 关联函数 combined —— 两个参数都转移所有权 ----          // 原代码注释分界线
    let c1 = Counter::new(100);                                     // 创建实例 c1 (知识点：变量绑定)
    let c2 = Counter::new(200);                                     // 创建实例 c2 (知识点：变量绑定)
    let c3 = Counter::combined(c1, c2);                             // 调用 associated function，将 c1 和 c2 按值传入，它们的所有权被完全转移 (Move) (知识点：函数调用的参数所有权转移)
    // println!("{}", c1.get_number()); // 编译错误！c1 已被 move       // 原代码注释：c1 已失效 (知识点：所有权安全保护)
    // println!("{}", c2.get_number()); // 编译错误！c2 已被 move       // 原代码注释：c2 也已失效 (知识点：所有权安全保护)
    println!("c3.number = {}", c3.get_number());                    // combined 聚合返回的新实例 c3 拥有完全的所有权，可以正常调用借用方法 (知识点：返回值接收所有权)

    // ---- 示例5: Point 的 self 所有权转移 ----                       // 原代码注释分界线
    let p = Point { x: 3.14 };                                      // 直接实例化 Point 结构体 (知识点：结构体字面量实例化)
    println!("p.x = {}", p.get());                                  // 调用 Point::get。因为 get 方法接收 self，p 的所有权被 Move 进去 (知识点：方法调用的隐式所有权转移)
    // println!("{}", p.x); // 编译错误！p 已被 move                    // 原代码注释：p 已经在上一行被消费，无法再访问内部字段 (知识点：部分访问也会因整体所有权丢失被拒绝)
}                                                                   // main 函数结束，剩余活跃变量 (c3) 顺次释放 (知识点：自动清理 Drop)