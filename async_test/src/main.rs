use std::time::Duration;

fn main() {
    // `trpl::block_on` 是异步运行的入口点。
    // 它阻塞当前线程，直到内部的 `async` 块执行完成。
    // 这相当于异步世界的 `main` 函数启动器。
    trpl::block_on(async {
        // ---------------------------------------------------------
        // 1. 创建异步通道 (Channel)
        // ---------------------------------------------------------
        // `trpl::channel()` 创建了一个异步的通信管道。
        // 返回一个元组：(发送者 tx, 接收者 rx)。
        // - tx (Transmitter): 用于发送数据。
        // - rx (Receiver): 用于接收数据。
        // 注意：这里没有显式指定缓冲区大小，通常默认为有界或无界，具体取决于 trpl 实现。
        let (tx, mut rx) = trpl::channel();

        // ---------------------------------------------------------
        // 2. 定义发送任务 (Sender Future)
        // ---------------------------------------------------------
        // 我们创建一个异步块来专门负责发送数据。
        // 关键点：使用 `async move`。
        // - `move`: 强制闭包获取其使用变量的所有权。这里必须获取 `tx` 的所有权，
        //   因为我们将把这个闭包作为独立的任务运行，它需要拥有自己的 `tx` 副本。
        // - 如果没有 `move`，`tx` 的借用可能会在生命周期上产生冲突。
        let tx_fut = async move {
            // 准备要发送的数据列表
            let vals = vec![
                String::from("hi"),
                String::from("from"),
                String::from("the"),
                String::from("future"),
            ];

            // 遍历列表并逐个发送
            for val in vals {
                // 发送数据。
                // 注意：如果 `trpl::channel` 的 `send` 方法是异步的（返回 Future），
                // 这里通常需要 `.await`。但根据你之前的代码 `tx.send(val).unwrap()`，
                // 假设这里的 `send` 是同步完成的（或者立即放入缓冲区）。
                // 如果编译报错提示需要 await，请改为：`tx.send(val).await.unwrap();`
                tx.send(val).unwrap();

                // 模拟耗时操作：休眠 1 秒。
                // `.await` 让出控制权，允许其他任务（如下面的接收任务）在此期间运行。
                trpl::sleep(Duration::from_millis(1000)).await;
            }

            // 当这个 `async move` 块结束时，`tx` 变量会被丢弃 (drop)。
            // 在所有发送者都被丢弃后，通道会关闭，接收方的 `recv()` 将返回 `None`。
        };

        // ---------------------------------------------------------
        // 3. 定义接收任务 (Receiver Future)
        // ---------------------------------------------------------
        // 创建另一个异步块专门负责接收数据。
        // 这里不需要 `move`，因为我们只是借用 `rx` (实际上 `rx` 没有被 `tx_fut` 移动走，
        // 但在这种模式下，通常 `rx` 只被这一个任务独占使用)。
        // 注意：`rx` 在 `tx_fut` 中未被使用，所以所有权依然在这里。
        let rx_fut = async {
            // 循环接收消息，直到通道关闭（即所有发送者都 drop 了）
            while let Some(value) = rx.recv().await {
                // `rx.recv().await` 是异步的：
                // - 如果有消息，立即返回 `Some(value)`。
                // - 如果没消息但通道还开着，挂起等待（让出 CPU）。
                // - 如果通道关闭，返回 `None`，循环结束。
                println!("received '{value}'");
            }
            println!("通道已关闭，接收结束。");
        };

        // ---------------------------------------------------------
        // 4. 并发执行 (Join)
        // ---------------------------------------------------------
        // `trpl::join` 并发地运行两个 future (`tx_fut` 和 `rx_fut`)。
        // - 它不会按顺序执行（先跑完 tx 再跑 rx）。
        // - 它会同时调度两者。
        // - 只有当**两个** future 都完成后，`join` 才会返回。
        //
        // 执行流程预测：
        // 1. tx_fut 发送 "hi"，然后 sleep 1秒。
        // 2. 在 tx 睡眠期间，rx_fut 醒来，收到 "hi" 并打印，然后因没数据而等待。
        // 3. 1秒后，tx_fut 醒来，发送 "from"，再 sleep。
        // 4. rx_fut 收到 "from" 并打印...
        // 5. 如此往复，实现“边发边收”。
        trpl::join(tx_fut, rx_fut).await;

        // 当 join 返回时，意味着发送方发完了（且 tx 已 drop），接收方也收完了所有消息。
        println!("所有任务完成！");
    });
}
